            if (!ctx) return;

            const datasets = [
                {
                    label: 'Pickup (Sim)',
                    data: simPickup,
                    borderColor: '#4caf50',
                    showLine: true, pointRadius: 0, borderWidth: 2
                },
                {
                    label: 'Slack-off (Sim)',
                    data: simSlack,
                    borderColor: '#f44336',
                    showLine: true, pointRadius: 0, borderWidth: 2
                },
                {
                    label: 'Free Hanging (Sim)',
                    data: simFree,
                    borderColor: '#999999',
                    borderDash: [5, 3],
                    showLine: true, pointRadius: 0, borderWidth: 1.5
                },
                {
                    label: 'Rig Avg',
                    data: rigAvg,
                    borderColor: '#ff9800',
                    backgroundColor: 'rgba(255, 152, 0, 0.7)',
                    showLine: false, pointRadius: 3, borderWidth: 1,
                    pointStyle: 'circle'
                },
                {
                    label: 'Rig Min',
                    data: rigMin,
                    borderColor: 'rgba(255, 152, 0, 0.3)',
                    showLine: true, pointRadius: 0, borderWidth: 1,
                    borderDash: [2, 2], fill: false
                },
                {
                    label: 'Rig Max',
                    data: rigMax,
                    borderColor: 'rgba(255, 152, 0, 0.3)',
                    showLine: true, pointRadius: 0, borderWidth: 1,
                    borderDash: [2, 2], fill: '-1'
                }
            ];

            if (staticWeights.length > 0) {
                datasets.push({
                    label: 'Static Weight (Rig)',
                    data: staticWeights,
                    borderColor: '#00bcd4',
                    backgroundColor: 'rgba(0, 188, 212, 0.5)',
                    showLine: true, pointRadius: 2, borderWidth: 1.5,
                    pointStyle: 'triangle'
                });
            }

            new Chart(ctx, {
                type: 'scatter',
                data: { datasets: datasets },
                options: {
                    responsive: true,
                    maintainAspectRatio: false,
                    scales: {
                        x: {
                            title: { display: true, text: 'Measured Depth (m)' },
                            grid: { color: 'rgba(128,128,128,0.2)' }
                        },
                        y: {
                            title: { display: true, text: 'Hook Load (kDaN)' },
                            grid: { color: 'rgba(128,128,128,0.2)' }
                        }
                    },
                    plugins: {
                        tooltip: {
                            callbacks: {
                                label: function(context) {
                                    return context.dataset.label + ': ' + context.parsed.y.toFixed(1) + ' kDaN at ' + context.parsed.x.toFixed(0) + ' m';
                                }
                            }
                        }
                    }
                }
            });
        });
        """
    }

    // MARK: - Statistics Table

    private func generateStatsTable(_ comparison: ComparisonResult) -> String {
        var html = """
        <table>
            <thead>
                <tr>
                    <th>Zone</th>
                    <th>Stands</th>
                    <th>Mean (kDaN)</th>
                    <th>P10</th>
                    <th>P50</th>
                    <th>P90</th>
                    <th>Std Dev</th>
                </tr>
            </thead>
            <tbody>
        """

        for stat in comparison.zoneStats {
            html += """
                <tr>
                    <td>\(escapeHTML(stat.zone))</td>
                    <td>\(stat.count)</td>
                    <td>\(f1(stat.meanResidual))</td>
                    <td>\(f1(stat.p10))</td>
                    <td>\(f1(stat.p50))</td>
                    <td>\(f1(stat.p90))</td>
                    <td>\(f1(stat.stddev))</td>
                </tr>
            """
        }

        let o = comparison.overallStats
        html += """
                <tr class="total-row">
                    <td>\(escapeHTML(o.zone))</td>
                    <td>\(o.count)</td>
                    <td>\(f1(o.meanResidual))</td>
                    <td>\(f1(o.p10))</td>
                    <td>\(f1(o.p50))</td>
                    <td>\(f1(o.p90))</td>
                    <td>\(f1(o.stddev))</td>
                </tr>
            </tbody>
        </table>
        """
        return html
    }

    // MARK: - Helpers

    private func escapeHTML(_ str: String) -> String {
        str.replacingOccurrences(of: "&", with: "&amp;")
           .replacingOccurrences(of: "<", with: "&lt;")
           .replacingOccurrences(of: ">", with: "&gt;")
           .replacingOccurrences(of: "\"", with: "&quot;")
    }

    private func f0(_ v: Double) -> String { String(format: "%.0f", v) }
    private func f1(_ v: Double) -> String { String(format: "%.1f", v) }
}
