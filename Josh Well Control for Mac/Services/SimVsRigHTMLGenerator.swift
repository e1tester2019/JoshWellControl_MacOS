struct SimVsRigHTMLData {
    let wellName: String
    let importName: String
    let tripType: String
    let generatedDate: Date
    // Sim data (arrays of same length, sorted by MD)
    let simMD: [Double]
    let simPickup_kDaN: [Double]
    let simSlackOff_kDaN: [Double]
    let simFreeHanging_kDaN: [Double]
    // Rig per-stand data
    let stands: [RigStandData]
    // Static weights (trip-in only)
    let staticWeights: [RigStaticWeight]
    // Zone boundaries (MD where zone changes)
    let zoneBoundaries: [(md: Double, zone: String)]
    // Statistics
    let comparison: ComparisonResult
}

class SimVsRigHTMLGenerator {
    static let shared = SimVsRigHTMLGenerator()
    private init() {}

    func generateHTML(for data: SimVsRigHTMLData) -> String {
        let dateFormatter = DateFormatter()
        dateFormatter.dateFormat = "d MMM yyyy, HH:mm"
        let dateStr = dateFormatter.string(from: data.generatedDate)

        let tripLabel = data.tripType == "in" ? "Trip In" : "Trip Out"
        let primaryLabel = data.tripType == "in" ? "Slack-off (Sim)" : "Pickup (Sim)"

        return """
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8">
            <meta name="viewport" content="width=device-width, initial-scale=1.0">
            <title>Sim vs Rig - \(escapeHTML(data.wellName)) - \(tripLabel)</title>
            <script src="https://cdn.jsdelivr.net/npm/chart.js@4.4.0/dist/chart.umd.min.js"></script>
            <style>\(generateCSS())</style>
        </head>
        <body>
            <header>
                <div class="header-content">
                    <h1>Sim vs Rig Comparison &mdash; \(tripLabel)</h1>
                    <span class="well-name">\(escapeHTML(data.wellName)) &bull; \(escapeHTML(data.importName))</span>
                </div>
            </header>
            <main>
                <section class="card">
                    <h2>Hook Load vs Depth</h2>
                    <div class="chart-wrapper">
                        <canvas id="compChart"></canvas>
                    </div>
                </section>

                <section class="card">
                    <h2>Residual Statistics (Rig \u{2212} Sim) &mdash; \(primaryLabel)</h2>
                    \(generateStatsTable(data.comparison))
                </section>
            </main>
            <footer>
                <p>Generated by Josh Well Control &mdash; \(dateStr)</p>
            </footer>
            <script>
            \(generateChartData(data))
            \(generateJavaScript(data))
            </script>
        </body>
        </html>
        """
    }

    #if os(macOS)
    func exportHTML(_ html: String, defaultName: String) {
        let savePanel = NSSavePanel()
        savePanel.allowedContentTypes = [.html]
        savePanel.nameFieldStringValue = defaultName
        savePanel.title = "Export Sim vs Rig Chart"

        if savePanel.runModal() == .OK, let url = savePanel.url {
            try? html.write(to: url, atomically: true, encoding: .utf8)
        }
    }
    #endif

