    // MARK: - Chart Data

    private func generateChartData(_ data: SimVsRigHTMLData) -> String {
        let simPickupJSON = zip(data.simMD, data.simPickup_kDaN).map { "{x:\(f1($0)),y:\(f1($1))}" }.joined(separator: ",")
        let simSlackJSON = zip(data.simMD, data.simSlackOff_kDaN).map { "{x:\(f1($0)),y:\(f1($1))}" }.joined(separator: ",")
        let simFreeJSON = zip(data.simMD, data.simFreeHanging_kDaN).map { "{x:\(f1($0)),y:\(f1($1))}" }.joined(separator: ",")

        let rigAvgJSON = data.stands.map { "{x:\(f1($0.standMidMD_m)),y:\(f1($0.avgHL_kDaN))}" }.joined(separator: ",")
        let rigMinJSON = data.stands.map { "{x:\(f1($0.standMidMD_m)),y:\(f1($0.minHL_kDaN))}" }.joined(separator: ",")
        let rigMaxJSON = data.stands.map { "{x:\(f1($0.standMidMD_m)),y:\(f1($0.maxHL_kDaN))}" }.joined(separator: ",")

        var staticJSON = "[]"
        if !data.staticWeights.isEmpty {
            staticJSON = "[" + data.staticWeights.map { "{x:\(f1($0.depth_m)),y:\(f1($0.hookLoad_kDaN))}" }.joined(separator: ",") + "]"
        }

        return """
        const simPickup = [\(simPickupJSON)];
        const simSlack = [\(simSlackJSON)];
        const simFree = [\(simFreeJSON)];
        const rigAvg = [\(rigAvgJSON)];
        const rigMin = [\(rigMinJSON)];
        const rigMax = [\(rigMaxJSON)];
        const staticWeights = \(staticJSON);
        const tripType = "\(data.tripType)";
        """
    }

    // MARK: - JavaScript

